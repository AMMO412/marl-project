"""Ordinary robot checkpoint demonstration; no task planner or combat behavior.

Coordinates and inline collision geometry come from the supplied SDF. Feedback
is generated by a bounded-speed kinematic simulator, not Gazebo or hardware.
"""
import argparse
import hashlib
import json
import math
from pathlib import Path
import shutil
import sys
import xml.etree.ElementTree as ET
from datetime import datetime

ROOT = Path(__file__).resolve().parent
PROJECT = ROOT.parent
sys.path.insert(0, str(PROJECT / 'planning_middle_demo'))
from city_nav import NavMap, distance, _combine, _pose, _box_polygon

SOURCE = PROJECT / '资料' / '接口说明' / 'container_00_combined_scene.sdf'


def read_scene(source=SOURCE):
    source = Path(source)
    root = ET.parse(source).getroot()
    world = root.find('world')
    if world is None:
        raise ValueError('SDF missing world')
    items, robots, unresolved = [], {}, []
    for model in world.findall('model'):
        name, pose = model.get('name'), _pose(model)
        if model.findtext('static') != 'true':
            robots[name] = dict(pose=pose, speed_limit=0.5)
            continue
        for link in model.findall('link'):
            for collision in link.findall('collision'):
                size = collision.findtext('geometry/box/size')
                if size is None:
                    raise ValueError('Unsupported static collision: ' + name)
                size = [float(v) for v in size.split()]
                transform = _combine(_combine(pose, _pose(link)), _pose(collision))
                top = transform[2] + size[2] / 2
                kind = ('ground' if name == 'env_lawn_ground' else
                        'road' if 'road_' in name or 'square' in name else
                        'wall' if 'walls_' in name else
                        'planter' if 'planter' in name else 'beacon')
                items.append(dict(id=name, kind=kind, size=size, pose=transform,
                                  polygon=_box_polygon(size[:2], transform),
                                  blocking=kind not in ('ground', 'road') and top > 0.2))
    for include in world.findall('include'):
        unresolved.append(dict(id=include.findtext('name'), uri=include.findtext('uri'),
                               pose=_pose(include), status='missing_geometry',
                               scale=include.findtext('scale')))
    return dict(world=world.get('name'), version=root.get('version'), items=items,
                robots=robots, unresolved=unresolved,
                bounds=[-290, -230, 290, 230],
                source=str(source), sha256=hashlib.sha256(source.read_bytes()).hexdigest(),
                geometry_complete=not unresolved)


def peer_obstacle(pid, p, radius):
    # Circumscribed polygon: conservatively encloses a stationary robot disc.
    r = radius / math.cos(math.pi / 8)
    return dict(id=pid, polygon=[[p[0] + r * math.cos(i * math.pi / 4),
                                 p[1] + r * math.sin(i * math.pi / 4)] for i in range(8)])


def simulate(scene, config):
    ids = config['robots']
    if len(ids) < 2 or len(ids) != len(set(ids)):
        raise ValueError('Select at least two distinct robots')
    if any(pid not in scene['robots'] or not 1 <= int(pid.split('_')[-1]) <= 20 for pid in ids):
        raise ValueError('Demo supports ordinary wheel robots 001-020')
    speed, dt = config['speed_mps'], config['dt_seconds']
    radius, margin = config['robot_radius_m'], config['margin_m']
    timeout = config['timeout_seconds']
    if not all(isinstance(v, (int, float)) and math.isfinite(v) and v > 0
               for v in [speed, dt, radius, margin, timeout]) or speed > 0.5 or dt > 2:
        raise ValueError('Invalid finite positive motion limits; speed<=0.5, dt<=2')
    if radius < 1.4:
        raise ValueError('Robot envelope must cover declared chassis and wheels (>=1.4m)')
    # This explicitly approved demonstration area excludes unresolved model origins.
    # It does NOT establish the unknown external models' footprints outside it.
    bounds = [-24, -125, 150, 35]
    obstacles = [x for x in scene['items'] if x['blocking']]
    nav = NavMap(bounds, obstacles, radius=radius + margin, resolution=1.0)
    poses = {pid: list(scene['robots'][pid]['pose'][:2]) for pid in ids}
    stages = [('移动到集合点', config['assembly'])] + [
        ('检查点%d' % (i + 1), row) for i, row in enumerate(config['checkpoints'])]
    if not config['checkpoints']:
        raise ValueError('At least one checkpoint required')
    for stage, targets in stages:
        if len(targets) != len(ids) or any(len(p) != 2 or not nav.free(p) for p in targets):
            raise ValueError('Invalid or obstructed targets: ' + stage)
        if any(distance(a, b) <= 2 * radius + margin for i, a in enumerate(targets)
               for b in targets[i + 1:]):
            raise ValueError('Targets too close: ' + stage)
    if any(not nav.free(p) for p in poses.values()):
        raise ValueError('Invalid start')
    if any(distance(a, b) <= 2 * radius + margin for i, a in enumerate(poses.values())
           for b in list(poses.values())[i + 1:]):
        raise ValueError('Starts too close')
    frames, paths, events = [], [], []
    t = 0.0
    active, stage, path_id = None, '接收任务', None
    min_peer, min_static = math.inf, math.inf

    def snapshot():
        nonlocal min_peer, min_static
        vals = list(poses.values())
        min_peer = min(min_peer, *(distance(a, b) for i, a in enumerate(vals) for b in vals[i+1:]))
        min_static = min(min_static, *(nav.clearance(p) - radius for p in vals))
        frames.append(dict(t=t, stage=stage, active=active, path_id=path_id,
                           poses={k: list(v) for k, v in poses.items()}))

    snapshot()
    for stage, targets in stages:
        events.append(dict(t=t, kind='stage_started', stage=stage))
        for index, pid in enumerate(ids):
            active = pid
            local = NavMap(bounds, obstacles + [peer_obstacle(k, p, radius) for k, p in poses.items() if k != pid],
                           radius=radius + margin, resolution=1.0)
            planned = local.plan(poses[pid], targets[index], densify=0)
            path_id = len(paths)
            paths.append(dict(id=path_id, pid=pid, stage=stage, start_t=t, **planned))
            snapshot()
            for target in planned['path'][1:]:
                while distance(poses[pid], target) > 1e-8:
                    before = poses[pid][:]
                    d = distance(before, target)
                    step = min(speed * dt, d)
                    after = [before[j] + (target[j] - before[j]) * step / d for j in (0, 1)]
                    if not local.segment_free(before, after):
                        raise RuntimeError('Swept path blocked')
                    poses[pid] = after
                    t += dt
                    if t > timeout:
                        raise RuntimeError('Task timeout')
                    snapshot()
            events.append(dict(t=t, kind='arrived', stage=stage, pid=pid, pos=poses[pid][:]))
        if not all(distance(poses[pid], targets[i]) < 1e-6 for i, pid in enumerate(ids)):
            raise RuntimeError('Arrival barrier failed')
        active, path_id = None, None
        stage = '全员到齐' if stage == '移动到集合点' else stage + '全员完成'
        events.append(dict(t=t, kind='all_arrived', stage=stage))
        t += dt
        snapshot()
    stage, active, path_id = '完成反馈', None, None
    t += dt
    snapshot()
    feedback = dict(task_id=config['task_id'], status='completed', backend='kinematic',
                    physical_execution_verified=False, geometry_complete=scene['geometry_complete'],
                    simulation_seconds=t, robot_ids=ids, checkpoint_count=len(config['checkpoints']),
                    min_robot_center_distance_m=min_peer, min_body_static_clearance_m=min_static,
                    final_positions=poses, traffic_policy='one_robot_at_a_time',
                    limitation='Only inline known geometry; unresolved external geometry is excluded from navigation evidence.')
    return dict(scene=scene, config=config, navigation_bounds=bounds,
                frames=frames, paths=paths, events=events, feedback=feedback)


def export(payload, out):
    out.mkdir(parents=True, exist_ok=False)
    for name, content in [('scene.json', payload['scene']), ('command.json', payload['config']),
                          ('feedback.json', payload['feedback']), ('events.json', payload['events']),
                          ('paths.json', payload['paths'])]:
        (out / name).write_text(json.dumps(content, ensure_ascii=False, indent=2), encoding='utf-8')
    (out / 'trace.jsonl').write_text(''.join(json.dumps(f, ensure_ascii=False) + '\n' for f in payload['frames']), encoding='utf-8')
    data = json.dumps(payload, ensure_ascii=False).replace('<', '\\u003c')
    html = (ROOT / 'viewer.html').read_text(encoding='utf-8').replace('/*PAYLOAD*/null', data)
    (out / 'index.html').write_text(html, encoding='utf-8')
    shutil.copy2(payload['scene']['source'], out / 'source.sdf')
    reference = ROOT / 'assets' / 'reference.png'
    if reference.exists():
        shutil.copy2(reference, out / 'reference.png')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--config', type=Path, default=ROOT / 'scenario.json')
    parser.add_argument('--out', type=Path)
    args = parser.parse_args()
    config = json.loads(args.config.read_text(encoding='utf-8-sig'))
    result = simulate(read_scene(), config)
    out = args.out or ROOT / 'outputs' / datetime.now().strftime('run_%Y%m%d_%H%M%S_%f')
    export(result, out)
    print(json.dumps(result['feedback'], ensure_ascii=True))
    print(str((out / 'index.html').resolve()))


if __name__ == '__main__':
    main()
